"""Write docs/CASES_V3_COMPARISON.md: every stored run scored under the ORIGINAL expectations and under the reviewer-based v3 expectations.

Offline, deterministic; reads bench/runs/*.json (original-expectation files and *_m3_career_cases_v3.json rescores).
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from bench import metrics  # noqa: E402

RUNS = ROOT / "bench" / "runs"
PAIRS = [  # label, old file, new file
    ("Rule engine, 22 dev cases", "career_rule_2026-10-27_m2.json", "career_rule_2026-10-27_m3_career_cases_v3.json"),
    ("Direct AI prompt (Haiku), 22 dev cases", "career_llm_direct_anthropic_claude-haiku-5.5_2026-10-27_m2.json",
     "career_llm_direct_anthropic_claude-haiku-5.5_2026-10-27_m3_career_cases_v3.json"),
    ("Evidence pipeline, tune split", "career_llm_evidence_nvidia_nemotron-3.5-super-vl_free_tune_2026-10-27.json",
     "career_llm_evidence_nvidia_nemotron-3.5-super-vl_free_tune_2026-10-27_m3_career_cases_v3.json"),
    ("Evidence pipeline, first holdout (used)", "career_llm_evidence_nvidia_nemotron-3.5-super-vl_free_holdout_2026-10-29.json",
     "career_llm_evidence_nvidia_nemotron-3.5-super-vl_free_holdout_2026-10-29_m3_career_cases_v3.json"),
    ("Rule engine, fresh set v2", "career_rule_holdout_v2_2026-10-29.json", "career_rule_holdout_v2_2026-10-29_m3_career_cases_v3.json"),
    ("Evidence pipeline, fresh set v2", "career_llm_evidence_nvidia_nemotron-3.5-super-vl_free_holdout_v2_2026-10-29.json",
     "career_llm_evidence_nvidia_nemotron-3.5-super-vl_free_holdout_v2_2026-10-29_m3_career_cases_v3.json"),
    ("Evidence pipeline, c20 rerun", "career_llm_evidence_nvidia_nemotron-3.5-super-vl_free_2026-10-28.json",
     "career_llm_evidence_nvidia_nemotron-3.5-super-vl_free_2026-10-28_m3_career_cases_v3.json"),
]


def load(n):
    return json.loads((RUNS / n).read_text(encoding="utf-8"))


def row(label, old, new):
    o, n = old["aggregate"]["overall"], new["aggregate"]["overall"]
    g = lambda d, k: d.get(k, "n/a")      # noqa: E731
    return (f"| {label} | {o['n_cases']} | {o['domain_confusion_cases']} | {n['domain_confusion_cases']} | {o['supported_recall']} | "
            f"{n['supported_recall']} | {g(n, 'overclaim_cases')} | {o['mean_areas_displayed']} | {o['top1_in_authored_ok_set']} | "
            f"{n['top1_in_authored_ok_set']} |")


def main():
    cases3 = {c["id"]: c for c in metrics.load_cases(ROOT / "bench" / "cases" / "career_cases_v3.yaml")}
    L = ["# Case expectations v3 vs original (reviewer changes applied as a new version)", "",
         "Generated by `scripts/compare_case_versions.py` from stored runs; nothing was re-run against a model. Original expectation files "
         "are unchanged (`bench/cases/career_cases.yaml`, `career_cases_holdout_v2.yaml`); v3 is `bench/cases/career_cases_v3.yaml` "
         "(per-case reasons in its `v3_change` field).", "",
         "**Read this first.** The reviewer's desk review (provisional, AI-assisted, not a practitioner) happened after the pipeline's outputs "
         "on these cases were known to the team, and several v3 changes move results in the pipeline's favour. v3 scores are therefore "
         "NOT independent evidence. Compare them with the original columns, and treat any gain that comes only from changed expectations "
         "as unproven until a practitioner confirms the change.", "",
         "## 1. Aggregates (old expectation | v3 expectation)", "",
         "| Run | Cases | Trap cases (old) | Trap cases (v3) | Expected areas found (old) | (v3) | Overclaim cases (v3) | Mean areas shown | Top-1 ok (old) | (v3) |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    runs = {}
    for label, o, n in PAIRS:
        old, new = load(o), load(n)
        runs[label] = (old, new)
        L.append(row(label, old, new))
    L += ["", "Overclaim = an area the reviewer says is fine only as labelled exploration, shown as a supported recommendation. "
          "The rule engine and the direct prompt have no exploration list, so every exploration-only area they show counts as an overclaim "
          "by construction; compare overclaims between pipeline runs, not against them.", ""]

    L += ["## 2. Which per-case results flipped because of the new expectations (evidence pipeline runs)", "",
          "| Run | Case | Expected areas found (old) | (v3) | Overclaims (v3) | What changed in the expectation |", "|---|---|---|---|---|---|"]
    for label in [p[0] for p in PAIRS if "Evidence" in p[0]]:
        old, new = runs[label]
        for cid, nm in new["per_case"].items():
            om = old["per_case"].get(cid)
            if om is None:
                continue
            c = cases3[cid]
            o_found, n_found = f"{len(om['supported_found'])}/{len(c['supported_v1'])}", f"{len(nm['supported_found'])}/{len(c['supported'])}"
            if o_found != n_found or nm.get("overclaims") or set(c["supported"]) != set(c["supported_v1"]):
                L.append(f"| {label} | {cid} | {o_found} | {n_found} | {', '.join(nm.get('overclaims', [])) or '-'} | {c['v3_change'][:150]} |")
    L += ["", "## 3. Every v3 change, with the reviewer's reason", "", "| Case | Supported (old) | Supported (v3) | Exploration only (v3) | Reason |", "|---|---|---|---|---|"]
    for cid, c in cases3.items():
        if c["v3_change"].startswith(("No reviewer", "Reviewer agreed", "Reviewer:", "Reviewer row")):
            continue
        L.append(f"| {cid} | {', '.join(c['supported_v1']) or '-'} | {', '.join(c['supported']) or '-'} | {', '.join(c['exploration_only']) or '-'} | {c['v3_change']} |")
    L += ["", "Unchanged by the reviewer: " + ", ".join(cid for cid, c in cases3.items() if c['v3_change'].startswith(('No reviewer', 'Reviewer agreed', 'Reviewer:', 'Reviewer row'))) + ".", ""]
    dest = ROOT / "docs" / "CASES_V3_COMPARISON.md"
    dest.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", dest.relative_to(ROOT))


if __name__ == "__main__":
    main()
